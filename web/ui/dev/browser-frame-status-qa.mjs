// Real Vue, controlled state/frame responses. Never touches a deployed session.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from '../../../browser-runtime/node_modules/playwright/index.mjs';
const base = process.argv[2] || 'http://127.0.0.1:5189';
const output = process.argv[3] || '/tmp/pogo-browser-frame-status';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const checks = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); console.log(`PASS ${name}`); };
try {
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 960 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route(url => url.pathname.startsWith('/api/'), route => route.abort());
    await page.goto(`${base}/dev/immersive-browser.html`);
    const refresh = () => page.getByRole('button', { name: '刷新画面', exact: true }).click();
    const image = page.locator('.native-page img');
    const requests = () => page.evaluate(() => window.__immersiveFixture.requests.filter(req => req.path.endsWith('/browser/frame')).length);
    const label = () => page.locator('.connection-dot').getAttribute('aria-label');
    await image.waitFor();
    if (width === 390) {
      await page.locator('.immersion-toggle').click();
      await page.locator('.shell.browser-immersive').waitFor();
      await page.locator('.immersive-chat-head > button').first().click();
    }
    await page.getByRole('button', { name: '停止 Agent 并接管', exact: true }).click();
    await page.locator('.native-page:not(.readonly)').waitFor();
    const oldFrame = await image.getAttribute('src');
    await page.evaluate(() => { window.__immersiveFixture.frameStatus = 409; });
    await refresh();
    await page.locator('.native-frame-status').filter({ hasText: '画面更新中' }).waitFor();
    check(`${width}: frame409 retains successful state connection`, (await label()).includes('已连接') && await page.locator('.native-error').count() === 0);
    const retainedFrame = await image.getAttribute('src');
    check(`${width}: frame409 retains last image without accepting old pixels`, !!retainedFrame && await page.locator('.native-page.readonly').count() === 1 && await page.getByRole('button', { name: '选取页面元素', exact: true }).isDisabled());
    let before = await page.evaluate(() => window.__immersiveFixture.inputs.length);
    await image.click();
    await page.locator('.native-page').focus();
    await page.keyboard.press('Enter');
    await image.hover(); await page.mouse.wheel(0, 30);
    check(`${width}: stale frame cannot dispatch click key or wheel`, await page.evaluate(() => window.__immersiveFixture.inputs.length) === before);
    await page.locator('.native-text textarea').fill('Draft retained while waiting');
    check(`${width}: stale frame cannot submit typed draft`, await page.getByRole('button', { name: '发送文字', exact: true }).isDisabled());
    const frameCalls = await requests();
    await page.waitForFunction(count => window.__immersiveFixture.requests.filter(req => req.path.endsWith('/browser/frame')).length >= count + 2, frameCalls);
    check(`${width}: repeated frame conflicts retry without reconnect or replay`, (await label()).includes('已连接') && await image.getAttribute('src') === retainedFrame && await page.evaluate(() => window.__immersiveFixture.inputs.length) === before);
    await page.screenshot({ path: `${output}/changing-${width}.png` });
    await page.evaluate(() => { window.__immersiveFixture.frameStatus = 502; window.__immersiveFixture.frameError = 'Fixture screenshot timeout'; });
    await refresh();
    await page.locator('.native-frame-status.unavailable').waitFor();
    check(`${width}: frame502 is frame unavailable, not disconnected`, (await label()).includes('已连接') && await page.locator('.native-error').count() === 0 && (await page.locator('.native-frame-status').getAttribute('title')).includes('Fixture screenshot timeout'));
    await page.screenshot({ path: `${output}/unavailable-${width}.png` });
    await page.evaluate(() => { window.__immersiveFixture.frameStatus = 200; window.__immersiveFixture.frameViewOnly = true; });
    await refresh();
    await page.locator('.native-frame-status').filter({ hasText: '当前画面仅供查看' }).waitFor();
    check(`${width}: unversioned fresh JPEG is labelled view-only`, await image.getAttribute('src') !== retainedFrame && (await label()).includes('已连接') && await page.locator('.native-page.readonly').count() === 1);
    await image.click(); await page.locator('.native-page').focus(); await page.keyboard.press('Enter'); await image.hover(); await page.mouse.wheel(0, 20);
    check(`${width}: view-only JPEG cannot drive input or picking`, await page.evaluate(() => window.__immersiveFixture.inputs.length) === before && await page.getByRole('button', { name: '选取页面元素', exact: true }).isDisabled() && await page.getByRole('button', { name: '发送文字', exact: true }).isDisabled());
    const address = page.getByRole('textbox', { name: '原站地址', exact: true });
    await address.fill('https://view-only.invalid/continuation'); await address.press('Enter');
    await page.waitForFunction(count => window.__immersiveFixture.inputs.length === count + 1, before);
    check(`${width}: view-only frame still permits explicit address navigation`, await page.evaluate(() => window.__immersiveFixture.inputs.at(-1).type === 'navigate' && window.__immersiveFixture.inputs.at(-1).url === 'https://view-only.invalid/continuation'));
    before++;
    await page.locator('.native-frame-status').filter({ hasText: '当前画面仅供查看' }).waitFor();
    await page.screenshot({ path: `${output}/view-only-${width}.png` });
    await page.evaluate(() => { window.__immersiveFixture.frameViewOnly = false; });
    await page.evaluate(() => { window.__immersiveFixture.patch({ busy: true }); window.__immersiveFixture.frameStatus = 409; });
    await refresh();
    await page.getByText('浏览器操作仍在执行，正在等待结果。', { exact: true }).waitFor();
    check(`${width}: pending action remains visible without connection failure`, (await label()).includes('已连接') && await page.getByRole('textbox', { name: '原站地址', exact: true }).evaluate(input => input.readOnly));
    await page.evaluate(() => { window.__immersiveFixture.patch({ debugger_paused: true }); });
    const pausedFrames = await requests();
    await refresh();
    await page.locator('.native-activity').filter({ hasText: '调试器已暂停页面' }).waitFor();
    check(`${width}: debugger pause clears frame warning and skips capture`, await page.locator('.native-frame-status').count() === 0 && await requests() === pausedFrames && (await label()).includes('已连接'));
    await page.evaluate(() => { window.__immersiveFixture.patch({ debugger_paused: false, busy: false }); window.__immersiveFixture.frameStatus = 200; });
    await refresh();
    await page.locator('.native-page:not(.readonly)').waitFor();
    check(`${width}: fresh frame after resume restores input and selection`, await image.getAttribute('src') !== oldFrame && await page.locator('.native-frame-status').count() === 0 && await page.getByRole('button', { name: '选取页面元素', exact: true }).isEnabled());
    check(`${width}: frame recovery preserves draft without submitting it`, await page.locator('.native-text textarea').inputValue() === 'Draft retained while waiting' && await page.evaluate(() => window.__immersiveFixture.inputs.length) === before);
    await page.evaluate(() => { window.__immersiveFixture.offline = true; });
    await refresh();
    await page.locator('.native-error').waitFor();
    check(`${width}: state503 is genuine connection failure`, (await label()).includes('连接中断') && await page.locator('.native-frame-status').count() === 0);
    await page.evaluate(() => { window.__immersiveFixture.offline = false; });
    await refresh();
    await page.locator('.native-page:not(.readonly)').waitFor();
    check(`${width}: state and frame recovery clear connection failure`, (await label()).includes('已连接') && await page.locator('.native-error').count() === 0);
    check(`${width}: no client errors or escaped requests`, errors.length === 0 && await page.evaluate(() => window.__immersiveFixture.denied.length) === 0);
    await page.screenshot({ path: `${output}/recovered-${width}.png` });
    await context.close();
  }
  await fs.writeFile(`${output}/after.json`, JSON.stringify({ kind: 'controlled UI fixture; not evidence that all observed live failures were409', passed: true, checks }, null, 2));
} finally { await browser.close(); }
