// The vision probe: three pictures whose contents are known by construction,
// one multiple-choice question each, and the verdict reads off the marks.
//
// There is no capabilities endpoint to ask — /models lists ids, not
// modalities — so the only portable test is empirical: send the image and see
// what comes back. But "can you see images?" is the wrong question to put to
// the model, because a text-only model behind a lenient gateway will happily
// describe a picture it never received. The questions are therefore about
// content only eyes can know (a colour, a digit, a count), four options each,
// and the model must answer with the option letter — a reply that is graded
// by string match, not by judgement. All three must pass: one question is a
// coin flip that a guessing model wins a quarter of the time, three in a row
// is 1/64, and the false "vision: true" is the expensive direction (pogo
// would then inline pixels to a model that cannot read them, and every image
// message fails at the provider instead of detouring through the vision
// helper).
//
// The pictures are generated by visionprobe/gen.py — solid colour, printed
// digit, counted circles, a few hundred bytes each — rather than samples from
// a VQA benchmark: a capability probe needs known answers, not benchmark
// difficulty, and self-drawn pixels carry no licence and no download.

//go:embed visionprobe/color.png
var probeColorPNG []byte

//go:embed visionprobe/digit.png
var probeDigitPNG []byte

//go:embed visionprobe/count.png
var probeCountPNG []byte

// visionQuestion is one graded item: an image, what to ask about it, and the
// option index that is true of its pixels.
type visionQuestion struct {
	Image   []byte
	Ask     string
	Options []string
	Answer  int // index into Options, 0 = A
}

var visionQuestions = []visionQuestion{
	{
		Image:   probeColorPNG,
		Ask:     "图中的大色块是什么颜色？\nA. 红色\nB. 蓝色\nC. 紫色\nD. 黄色\n只回答选项字母。",
		Options: []string{"红色", "蓝色", "紫色", "黄色"},
		Answer:  2,
	},
	{
		Image:   probeDigitPNG,
		Ask:     "图中印刷的黑色数字是几？\nA. 1\nB. 7\nC. 3\nD. 9\n只回答选项字母。",
		Options: []string{"1", "7", "3", "9"},
		Answer:  1,
	},
	{
		Image:   probeCountPNG,
		Ask:     "图中黑色圆形有几个？\nA. 3\nB. 2\nC. 4\nD. 5\n只回答选项字母。",
		Options: []string{"3", "2", "4", "5"},
		Answer:  0,
	},
}

// visionLetterRe matches an option letter standing alone — surrounded by
// anything that is not a letter, so "C." and "答案是C" and "the answer is C"
// all yield C while the A in "Image" does not match.
var visionLetterRe = regexp.MustCompile(`(?:^|[^A-Za-z])([A-Da-d])(?:[^A-Za-z]|$)`)

// gradeVisionReply marks one reply against its question. The letter is the
// primary reading because the prompt demands it; a model that ignored the
// instruction and wrote the option's text is still read, since the point is
// whether it saw the picture, not whether it follows formatting.
func gradeVisionReply(reply string, q visionQuestion) bool {
	if m := visionLetterRe.FindStringSubmatch(reply); m != nil {
		return int(m[1][0]&^0x20-'A') == q.Answer
	}
	trimmed := strings.TrimSpace(reply)
	for i, opt := range q.Options {
		if trimmed == opt || strings.Contains(trimmed, opt) {
			return i == q.Answer
		}
	}
	return false
}

// imageRejectWords appear in provider errors that mean "this model/endpoint
// does not take image content". Matched case-insensitively against the error
// body, in English and in the words the Chinese gateways use.
var imageRejectWords = []string{
	"image", "vision", "multimodal", "multi-modal", "multi_modal", "图片",
}

// imageRejected reports whether an error body is the endpoint saying no to
// pixels specifically — distinct from a bad key or a wrong model name, which
// say nothing about vision and leave the question open.
func imageRejected(body string) bool {
	low := strings.ToLower(body)
	for _, w := range imageRejectWords {
		if strings.Contains(low, w) {
			return true
		}
	}
	return false
}

type visionProbeQuestionResult struct {
	Ask     string   `json:"ask"`
	Options []string `json:"options"`
	Answer  string   `json:"answer"` // the letter, for display beside the reply
	Reply   string   `json:"reply"`
	Pass    bool     `json:"pass"`
}

type visionProbeResult struct {
	OK        bool                        `json:"ok"`
	Error     string                      `json:"error,omitempty"`
	Verdict   string                      `json:"verdict,omitempty"` // "yes" | "no"
	Rejected  bool                        `json:"rejected,omitempty"`
	Note      string                      `json:"note,omitempty"`
	ElapsedMs int64                       `json:"elapsed_ms"`
	Questions []visionProbeQuestionResult `json:"questions"`
}

// handleVisionProbeQuestions hands the dialog the exact material it is about
// to send — the asks and the inline data URLs of the test images — so the
// curl preview can show the real request rather than a sketch of it.
// Read-only and secret-free: the probe's own endpoint decides where a key may
// go, this one sends nothing anywhere.
func (s *Server) handleVisionProbeQuestions(w http.ResponseWriter, r *http.Request) {
	qs := make([]map[string]any, 0, len(visionQuestions))
	for _, q := range visionQuestions {
		qs = append(qs, map[string]any{
			"ask":       q.Ask,
			"image_url": "data:image/png;base64," + base64.StdEncoding.EncodeToString(q.Image),
		})
	}
	writeJSON(w, http.StatusOK, map[string]any{"questions": qs})
}

// handleVisionProbe runs the three questions against one provider+model. The
// trust shape is handleProbeConfig's exactly: the server sits on the networks
// gateways live on, the key resolves typed-value-first then key_env, and an
// env-resolved key only rides to a host providers.json already names. The
// request body mirrors the multimodal wire form the agent itself sends
// (llm/convert.go), so a verdict here is a verdict about real traffic.
func (s *Server) handleVisionProbe(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Name      string            `json:"name"`
		BaseURL   string            `json:"base_url"`
		KeyEnv    string            `json:"key_env"`
		Key       string            `json:"key"`
		Model     string            `json:"model"`
		Headers   map[string]string `json:"headers"`
		ExtraBody map[string]any    `json:"extra_body"`
	}
	rawBody, err := io.ReadAll(http.MaxBytesReader(w, r.Body, 1<<20))
	if err != nil {
		writeErr(w, http.StatusBadRequest, err)
		return
	}
	if err := decodeLenientJSON(rawBody, &body); err != nil {
		writeErr(w, http.StatusBadRequest, fmt.Errorf("invalid JSON body: %w", err))
		return
	}
	u, err := url.Parse(strings.TrimSuffix(strings.TrimSpace(body.BaseURL), "/") + "/chat/completions")
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" {
		writeErr(w, http.StatusBadRequest, errors.New("base_url must be an absolute http(s) URL"))
		return
	}

	key := strings.TrimSpace(body.Key)
	envKey := ""
	if key == "" {
		envKey = envKeyFor(body.Name, body.KeyEnv)
		key = envKey
	}
	if envKey != "" && !configuredProviderHost(u.Hostname()) {
		writeErr(w, http.StatusBadRequest, fmt.Errorf(
			"probing %s with a server-resolved key is refused: the host is not in providers.json; type the key explicitly to send it to a new host", u.Hostname()))
		return
	}

	start := time.Now()
	res := visionProbeResult{}
	for _, q := range visionQuestions {
		content := []map[string]any{
			{"type": "text", "text": q.Ask},
			{"type": "image_url", "image_url": map[string]any{
				"url": "data:image/png;base64," + base64.StdEncoding.EncodeToString(q.Image),
			}},
		}
		// The payload is deliberately the connectivity probe's minimal shape
		// — model, messages, stream — plus nothing else. Optional knobs are
		// provider law: kimi's reasoning models reject any temperature but 1,
		// and a small max_tokens lets a thinking model spend the whole budget
		// on reasoning and return an empty answer, which would read as
		// "cannot see". Brevity is asked for in the prompt and bounded by the
		// deadline instead.
		payload := map[string]any{
			"model":    body.Model,
			"messages": []map[string]any{{"role": "user", "content": content}},
			"stream":   false, // forced: the grader reads one JSON body
		}
		for k, v := range body.ExtraBody {
			payload[k] = v // custom keys win — the merge rule everywhere else here
		}
		jsonBody, err := json.Marshal(payload)
		if err != nil {
			writeErr(w, http.StatusBadRequest, err)
			return
		}

		ctx, cancel := context.WithTimeout(r.Context(), 30*time.Second)
		req, err := http.NewRequestWithContext(ctx, http.MethodPost, u.String(), bytes.NewReader(jsonBody))
		if err != nil {
			cancel()
			writeErr(w, http.StatusBadRequest, err)
			return
		}
		req.Header.Set("Content-Type", "application/json")
		if key != "" {
			req.Header.Set("Authorization", "Bearer "+key)
		}
		for k, v := range body.Headers {
			if strings.TrimSpace(k) != "" {
				req.Header.Set(k, v)
			}
		}

		// A key is never re-posted across a redirect (the rule the config
		// probe set); a moved gateway is a finding, not somewhere to follow.
		client := http.DefaultClient
		if key != "" {
			client = &http.Client{
				CheckRedirect: func(req *http.Request, via []*http.Request) error {
					return http.ErrUseLastResponse
				},
			}
		}
		resp, err := client.Do(req)
		cancel()
		if err != nil {
			res.Error = err.Error()
			break
		}
		data, _ := io.ReadAll(io.LimitReader(resp.Body, 64<<10))
		resp.Body.Close()
		if resp.StatusCode != http.StatusOK {
			snippet := strings.TrimSpace(string(data))
			if len(snippet) > 400 {
				snippet = snippet[:400]
			}
			if resp.StatusCode >= 400 && imageRejected(snippet) {
				// The endpoint refused the pixels themselves: the model does
				// not see images on this route, and no further question will
				// change that.
				res.Verdict = "no"
				res.Rejected = true
				res.Note = fmt.Sprintf("HTTP %d: %s", resp.StatusCode, snippet)
				break
			}
			res.Error = fmt.Sprintf("HTTP %d: %s", resp.StatusCode, snippet)
			break
		}

		var parsed struct {
			Choices []struct {
				Message struct {
					Content string `json:"content"`
				} `json:"message"`
			} `json:"choices"`
			Error *struct {
				Message string `json:"message"`
			} `json:"error"`
		}
		if err := json.Unmarshal(data, &parsed); err != nil {
			res.Error = fmt.Sprintf("response is not JSON: %v", err)
			break
		}
		if parsed.Error != nil && parsed.Error.Message != "" {
			// Some gateways answer 200 and put the refusal in the body.
			if imageRejected(parsed.Error.Message) {
				res.Verdict = "no"
				res.Rejected = true
				res.Note = parsed.Error.Message
				break
			}
			res.Error = parsed.Error.Message
			break
		}
		reply := ""
		if len(parsed.Choices) > 0 {
			reply = strings.TrimSpace(parsed.Choices[0].Message.Content)
		}
		res.Questions = append(res.Questions, visionProbeQuestionResult{
			Ask:     q.Ask,
			Options: q.Options,
			Answer:  string(rune('A' + q.Answer)),
			Reply:   reply,
			Pass:    gradeVisionReply(reply, q),
		})
	}

	if res.Error == "" && res.Verdict == "" {
		res.OK = true
		res.Verdict = "yes"
		for _, qr := range res.Questions {
			if !qr.Pass {
				res.Verdict = "no"
				break
			}
		}
		res.ElapsedMs = time.Since(start).Milliseconds()
	}
	writeJSON(w, http.StatusOK, res)
}
